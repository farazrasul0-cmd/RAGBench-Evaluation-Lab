def escape_latex(text: str) -> str:
    """Escape LaTeX special characters to ensure error-free compilation."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "@": r"@{}",
    }
    res = text.replace("\\", replacements["\\"])
    for char, rep in replacements.items():
        if char != "\\":
            res = res.replace(char, rep)
    return res


class AcademicLatexExporter:
    """Generates peer-reviewed publication quality LaTeX tables using the booktabs package."""

    @classmethod
    def export_comparison_table(
        cls,
        report: MetricSignificanceReport,
        caption: str = "Empirical Comparison and Statistical Significance Analysis",
        label: str = "tab:ragbench_comparison",
        bold_maximum: bool = False,
    ) -> str:
        """Render publication-ready LaTeX table with booktabs typography and statistical bounds."""
        lines: list[str] = [
            "% Auto-generated by RAGBench Evaluation Lab",
            r"\begin{table*}[t]",
            r"\centering",
            r"\small",
            r"\begin{tabular}{lcccccc}",
            r"\toprule",
            (
                r"\textbf{Metric} & \textbf{Run 1} & \textbf{Run 2} & "
                r"\textbf{Mean $\Delta$} & \textbf{95\% CI ($\Delta$)} & "
                r"\textbf{Cohen's $d_z$} & \textbf{Adj. $p$ (Holm)} \\"
            ),
            r"\midrule",
        ]

        for m_name, res in sorted(report.metrics.items()):
            safe_metric = escape_latex(m_name)
            m1_val = res.mean_a
            m2_val = res.mean_b

            str_m1 = f"{m1_val:.4f}"
            str_m2 = f"{m2_val:.4f}"

            if bold_maximum:
                if m2_val > m1_val:
                    str_m2 = f"\\textbf{{{m2_val:.4f}}}"
                elif m1_val > m2_val:
                    str_m1 = f"\\textbf{{{m1_val:.4f}}}"

            sign = "+" if res.mean_difference >= 0 else ""
            str_delta = f"{sign}{res.mean_difference:.4f}"

            if res.ci95_lower is not None and res.ci95_upper is not None:
                str_ci = f"[{res.ci95_lower:+.4f}, {res.ci95_upper:+.4f}]"
            else:
                str_ci = "N/A"

            str_dz = f"{res.cohens_dz:+.2f}" if res.cohens_dz is not None else "N/A"

            if res.adjusted_p_value is not None:
                stars = res.significance_level
                if stars != "ns":
                    str_p = f"{res.adjusted_p_value:.4f}^{{{stars}}}"
                else:
                    str_p = f"{res.adjusted_p_value:.4f}"
            else:
                str_p = "N/A"

            row_tex = (
                f"{safe_metric} & {str_m1} & {str_m2} & {str_delta} & "
                f"{str_ci} & {str_dz} & {str_p} \\\\"
            )
            lines.append(row_tex)

        lines.extend(
            [
                r"\bottomrule",
                r"\end{tabular}",
                f"\\caption{{{caption}}}",
                f"\\label{{{label}}}",
                (
                    r"\begin{flushleft}\footnotesize "
                    + (
                        r"\textit{Note:} Bold numbers denote observed sample maximums. "
                        if bold_maximum
                        else r"\textit{Note:} Values report sample means. "
                    )
                    + (
                        r"Statistically significant paired differences under Holm--Bonferroni "
                        r"correction are denoted with "
                        r"$^{*}(p<0.05)$, $^{**}(p<0.01)$, $^{***}(p<0.001)$."
                    )
                    + r"\end{flushleft}"
                ),
                r"\end{table*}",
            ]
        )

        return "\n".join(lines)


class CSVExporter:
    """Exports structured comparative and raw observation data to CSV."""

    @classmethod
    def export_summary_csv(cls, report: MetricSignificanceReport) -> str:
        """Export aggregate statistical comparisons across metrics to CSV."""
        output = io.StringIO()
        writer = csv.writer(output)

        writer.writerow(
            [
                "metric",
                "mean_run_a",
                "mean_run_b",
                "mean_difference",
                "std_difference",
                "ci95_lower",
                "ci95_upper",
                "t_statistic",
                "t_df",
                "raw_p_value",
                "cohens_dz",
                "wilcoxon_statistic",
                "wilcoxon_pvalue",
                "adjustment_method",
                "adjusted_p_value",
                "significance_level",
                "n_paired",
            ]
        )

        for m_name, res in sorted(report.metrics.items()):
            writer.writerow(
                [
                    m_name,
                    f"{res.mean_a:.6f}",
                    f"{res.mean_b:.6f}",
                    f"{res.mean_difference:.6f}",
                    f"{res.std_difference:.6f}",
                    f"{res.ci95_lower:.6f}" if res.ci95_lower is not None else "",
                    f"{res.ci95_upper:.6f}" if res.ci95_upper is not None else "",
                    f"{res.t_statistic:.6f}" if res.t_statistic is not None else "",
                    str(res.t_df) if res.t_df is not None else "",
                    f"{res.raw_p_value:.6f}" if res.raw_p_value is not None else "",
                    f"{res.cohens_dz:.6f}" if res.cohens_dz is not None else "",
                    f"{res.wilcoxon_statistic:.6f}" if res.wilcoxon_statistic is not None else "",
                    f"{res.wilcoxon_pvalue:.6f}" if res.wilcoxon_pvalue is not None else "",
                    res.adjustment_method,
                    f"{res.adjusted_p_value:.6f}" if res.adjusted_p_value is not None else "",
                    res.significance_level,
                    res.alignment.n_paired,
                ]
            )

        return output.getvalue()

    @classmethod
    def export_raw_paired_csv(cls, report: MetricSignificanceReport) -> str:
        """Export query-by-query raw paired observations for audit and R/Pandas analysis."""
        output = io.StringIO()
        writer = csv.writer(output)

        writer.writerow(["query_id", "metric", "score_run_a", "score_run_b", "difference"])

        for m_name, res in sorted(report.metrics.items()):
            for obs in res.raw_paired_observations:
                writer.writerow(
                    [
                        obs.query_id,
                        m_name,
                        f"{obs.score_a:.6f}",
                        f"{obs.score_b:.6f}",
                        f"{obs.difference:.6f}",
                    ]
                )

        return output.getvalue()


class ReplicationArchiveExporter:
    """Packages complete academic replication archives with cryptographic manifests."""

    @classmethod
    def export_package(
        cls,
        report: MetricSignificanceReport,
        target_dir: Path,
        config_diff: dict[str, Any] | None = None,
    ) -> Path:
        """Write an authoritative, self-contained replication bundle to disk."""
        target_dir.mkdir(parents=True, exist_ok=True)

        files_to_hash: list[tuple[str, Path]] = []

        # 1. Statistical summary JSON
        summary_json_path = target_dir / "statistical_summary.json"
        summary_json_path.write_text(report.model_dump_json(indent=2), encoding="utf-8")
        files_to_hash.append(("statistical_summary.json", summary_json_path))

        # 2. LaTeX table
        latex_path = target_dir / "comparison_table.tex"
        latex_path.write_text(
            AcademicLatexExporter.export_comparison_table(report), encoding="utf-8"
        )
        files_to_hash.append(("comparison_table.tex", latex_path))

        # 3. CSV files
        summary_csv_path = target_dir / "statistical_summary.csv"
        summary_csv_path.write_text(CSVExporter.export_summary_csv(report), encoding="utf-8")
        files_to_hash.append(("statistical_summary.csv", summary_csv_path))

        raw_csv_path = target_dir / "raw_paired_observations.csv"
        raw_csv_path.write_text(CSVExporter.export_raw_paired_csv(report), encoding="utf-8")
        files_to_hash.append(("raw_paired_observations.csv", raw_csv_path))

        # 4. Pipeline configuration diff
        if config_diff:
            cfg_diff_path = target_dir / "config_diff.json"
            cfg_diff_path.write_text(json.dumps(config_diff, indent=2), encoding="utf-8")
            files_to_hash.append(("config_diff.json", cfg_diff_path))

        # 5. Environment & System manifest
        manifest_data = {
            "comparison_id": report.comparison_id,
            "run_a_id": report.run_a_id,
            "run_b_id": report.run_b_id,
            "dataset_version_id": report.dataset_version_id,
            "system_environment": {
                "os": platform.system(),
                "os_release": platform.release(),
                "python_version": sys.version,
                "machine": platform.machine(),
            },
            "metrics_evaluated": list(report.metrics.keys()),
            "adjustment_method": report.adjustment_method,
            "warmup_queries_excluded": report.warmup_queries_excluded,
        }
        manifest_path = target_dir / "manifest.json"
        manifest_path.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")
        files_to_hash.append(("manifest.json", manifest_path))

        # 6. Cryptographic SHA-256 Hashes Manifest
        hashes: dict[str, str] = {}
        for rel_name, f_path in files_to_hash:
            content_bytes = f_path.read_bytes()
            hashes[rel_name] = hashlib.sha256(content_bytes).hexdigest()

        hashes_path = target_dir / "hashes.json"
        hashes_path.write_text(json.dumps(hashes, indent=2), encoding="utf-8")

        return target_dir
